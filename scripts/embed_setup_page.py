"""Embed the QR setup page into a gzipped PROGMEM header for the firmware.

The hosted UI serves web/setup.html with external scripts. The device has no
filesystem, so the firmware copy inlines those scripts and gzip-compresses
the page. src/generated/ is build output and is not committed.
"""

import gzip
import pathlib

try:
    from SCons.Script import Import
    Import("env")
except Exception:
    env = None


def project_root():
    return pathlib.Path(__file__).resolve().parent.parent


def _inline_script(html, marker, source, label):
    if "</script>" in source.lower():
        raise RuntimeError("%s contains a closing script tag" % label)
    replacement = "<script>\n%s\n</script>" % source
    if marker not in html:
        raise RuntimeError("setup.html is missing %s" % marker)
    return html.replace(marker, replacement, 1)


def build_setup_page_html(root=None):
    """Return the self-contained setup page as UTF-8 bytes."""
    root = pathlib.Path(root) if root else project_root()
    html = (root / "web" / "setup.html").read_text(encoding="utf-8")
    vendor_path = root / "web" / "vendor" / "qrcode.js"
    vendor = vendor_path.read_text(encoding="utf-8")
    setup = (root / "web" / "setup.js").read_text(encoding="utf-8")
    html = _inline_script(
        html, '<script src="/vendor/qrcode.js"></script>', vendor, "qrcode.js"
    )
    html = _inline_script(
        html, '<script src="/setup.js"></script>', setup, "setup.js"
    )
    if 'src="/vendor/qrcode.js"' in html or 'src="/setup.js"' in html:
        raise RuntimeError("failed to inline setup scripts")
    return html.encode("utf-8")


def gzip_page(html_bytes):
    return gzip.compress(html_bytes, compresslevel=9, mtime=0)


def header_text(gz_bytes):
    lines = [
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#ifndef PROGMEM",
        "#define PROGMEM",
        "#endif",
        "// Generated by scripts/embed_setup_page.py. Do not edit.",
        "static const uint8_t SETUP_PAGE_GZ[] PROGMEM = {",
    ]
    row = []
    for byte in gz_bytes:
        row.append("0x%02x" % byte)
        if len(row) == 16:
            lines.append("  " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ", ".join(row) + ",")
    lines.append("};")
    lines.append("static const size_t SETUP_PAGE_GZ_LEN = %d;" % len(gz_bytes))
    lines.append("")
    return "\n".join(lines)


def write_header(root=None):
    root = pathlib.Path(root) if root else project_root()
    html = build_setup_page_html(root)
    gz_bytes = gzip_page(html)
    out_dir = root / "src" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "setup_page.h"
    path.write_text(header_text(gz_bytes), encoding="utf-8")
    return path, len(html), len(gz_bytes)


if env is not None:
    header_path, html_len, gz_len = write_header(env["PROJECT_DIR"])
    print(
        "[embed_setup_page] %s html=%d gzip=%d"
        % (header_path, html_len, gz_len)
    )
